export const TEMPLATE_MAP: ReadonlyMap<string, Template> = new Map(TEMPLATES.map((t) => [t.id, t]))

export const DEFAULT_TEMPLATE = 'newspaper'

export function getTemplate(id: string): Template {
  return TEMPLATE_MAP.get(id) ?? (TEMPLATE_MAP.get(DEFAULT_TEMPLATE) as Template)
}

/** Full settings for a template, including its sample copy. */
export function templateSettings(id: string, keepCopy?: { text: string; focus: string }): Settings {
  const t = getTemplate(id)
  return {
    ...BASE,
    ...t.settings,
    template: t.id,
    text: keepCopy?.text ?? t.sample.text,
    focus: keepCopy?.focus ?? t.sample.focus,
  }
}
